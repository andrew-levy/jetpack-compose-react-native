import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// EXPERIMENT: This is the downstream generator only. A source/KSP extractor
// must replace api-fixture.json before production codegen is possible.
const root = path.dirname(fileURLToPath(import.meta.url));
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'api-fixture.json'), 'utf8'));
const kinds = {
  string: {
    ts: 'string',
    kotlin: (p) => 'node.string("' + p.name + '")'
  },
  boolean: {
    ts: 'boolean',
    kotlin: (p) => 'node.boolean("' + p.name + '", ' + String(p.default) + ')'
  },
  modifier: {
    ts: 'ModifierChain',
    kotlin: (p) => 'node.modifier("' + p.name + '")'
  },
  event: {
    ts: '() => void',
    kotlin: (p) => '{ node.emit("' + p.name + '") }'
  }
};
function validate(schema) {
  if (schema.schemaVersion !== 1) throw Error('Unsupported manifest version');
  const names = new Set();
  for (const c of schema.components) {
    if (!/^[A-Za-z_]\w*$/.test(c.name) || names.has(c.name)) throw Error('Invalid/duplicate component: ' + c.name);
    if (!/^[A-Za-z_]\w*(\.[A-Za-z_]\w*)+$/.test(c.kotlinFunction)) throw Error('Invalid Kotlin call: ' + c.name);
    names.add(c.name);
    const props = new Set();
    for (const p of c.parameters) {
      if (!kinds[p.kind] || props.has(p.name)) throw Error('Unsupported/duplicate prop: ' + c.name + '.' + p.name);
      props.add(p.name);
      if (p.kind === 'boolean' && p.optional && typeof p.default !== 'boolean') throw Error('Missing boolean default: ' + c.name + '.' + p.name);
    }
  }
}
function makeTypeScript(schema) {
  const components = schema.components.map((c) => {
    const fields = c.parameters.map((p) => '  ' + p.name + (p.optional ? '?' : '') + ': ' + kinds[p.kind].ts + ';').join('\n');
    return 'export interface ' + c.name + 'Props {\n' + fields +
      (c.children ? '\n  children?: React.ReactNode;' : '') +
      '\n}\n\nexport const ' + c.name + ' = createComposable<' + c.name +
      'Props>({ name: "' + c.name + '", props: [' +
      c.parameters.map((p) => '"' + p.name + '"').join(', ') +
      '], children: ' + c.children + ' });';
  });
  return '// Generated by Compose PoC; do not edit.\n' +
    'import * as React from "react";\n' +
    'import { createComposable, type ModifierChain } from "../runtime/createComposable";\n\n' +
    components.join('\n\n') + '\n';
}
function makeKotlin(schema) {
  const branches = schema.components.map((c) => {
    const args = c.parameters.map((p) => '      ' + p.name + ' = ' + kinds[p.kind].kotlin(p));
    if (c.children) args.push('      content = { for (child in node.children) renderComposable(child) }');
    return '    "' + c.name + '" -> ' + c.kotlinFunction + '(\n' +
      args.join(',\n') + '\n    )';
  });
  return '// Generated by Compose PoC; do not edit.\n' +
    'package expo.modules.jetpackcomposereactnative.poc.generated\n\n' +
    'import androidx.compose.runtime.Composable\n' +
    'import expo.modules.jetpackcomposereactnative.poc.runtime.ComposeNode\n\n' +
    '@Composable\nfun renderComposable(node: ComposeNode) {\n  when (node.name) {\n' +
    branches.join('\n') +
    '\n    else -> error("Unknown composable: " + node.name)\n  }\n}\n';
}
validate(manifest);
const output = path.join(root, 'generated');
fs.mkdirSync(output, { recursive: true });
const files = {
  'components.tsx': makeTypeScript(manifest),
  'ComposableRegistry.kt': makeKotlin(manifest),
};
for (const [name, content] of Object.entries(files)) {
  const filename = path.join(output, name);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(filename) || fs.readFileSync(filename, 'utf8') !== content) {
      throw Error('Stale generated file: ' + name);
    }
  } else {
    fs.writeFileSync(filename, content);
  }
}
console.log((process.argv.includes('--check') ? 'Verified' : 'Generated') +
  ' ' + Object.keys(files).length + ' files for ' + manifest.components.length + ' composables');
